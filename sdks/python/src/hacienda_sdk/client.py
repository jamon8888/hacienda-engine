"""High-level client for the hacienda-engine API.

`HaciendaClient` (sync) and `AsyncHaciendaClient` (async) each wrap the generated
`AuthenticatedClient` (`_generated/client.py`, httpx-based) and expose one
namespace attribute per OpenAPI tag (`client.pii.scan_text(...)`,
`client.documents.process_documents(...)`, `client.auth.get_whoami()`, ...) —
one namespace class per tag, generated mechanically from `_generated/api/`'s
module list so a new route picked up by the next `scripts/generate.sh` run gets
a namespace method automatically the next time this file is regenerated by hand
from the same introspection (see `sdks/python/README.md`).

Every namespace method routes through `_detailed` generated functions and
`errors._unwrap`, never the plain `sync`/`asyncio` convenience functions —
those collapse every non-2xx response (including documented 401/403/404/400)
into `None`, which would make an error indistinguishable from an empty success.
"""

