class HaciendaClient:
    """Synchronous client. One namespace attribute per OpenAPI tag."""

    def __init__(
        self,
        base_url: str,
        api_key: str,
        *,
        target: Target = "cloud",
        timeout: float = 30.0,
        max_retries: int = 2,
        retry_statuses: frozenset[int] = _DEFAULT_RETRY_STATUSES,
        verify_ssl: bool | str = True,
    ) -> None:
        if target != "cloud":
            raise ValueError(f'unsupported target {target!r} — only "cloud" is implemented today')

        transport = _RetryTransport(
            httpx.HTTPTransport(verify=verify_ssl),
            max_retries=max_retries,
            retry_statuses=retry_statuses,
        )
        self._client = AuthenticatedClient(
            base_url=base_url,
            token=api_key,
            timeout=httpx.Timeout(timeout),
            verify_ssl=verify_ssl,
            httpx_args={"transport": transport},
        )
        self.info = _InfoNamespaceSync(self._client)
        self.documents = _DocumentsNamespaceSync(self._client)
        self.pii = _PiiNamespaceSync(self._client)
        self.jobs = _JobsNamespaceSync(self._client)
        self.audit = _AuditNamespaceSync(self._client)
        self.review = _ReviewNamespaceSync(self._client)
        self.compliance = _ComplianceNamespaceSync(self._client)
        self.glossary = _GlossaryNamespaceSync(self._client)
        self.auth = _AuthNamespaceSync(self._client)
        self.rag = _RagNamespaceSync(self._client)
        self.presets = _PresetsNamespaceSync(self._client)
        self.versions = _VersionsNamespaceSync(self._client)
        self.uploads = _UploadsNamespaceSync(self._client)
        self.usage = _UsageNamespaceSync(self._client)

    def whoami(self):
        """`GET /v1/auth/whoami` — the calling key's own granted capabilities.

        The capability probe a client should use to decide which methods will
        actually work against the supplied key, since hacienda has one tier
        (unlike xberg's `_resolve_tier`, which this replaces): see
        `hacienda-api/src/handlers/auth.rs`'s `whoami` doc comment.
        """
        return self.auth.get_whoami()

    def close(self) -> None:
        self._client.get_httpx_client().close()

    def __enter__(self) -> HaciendaClient:
        return self

    def __exit__(self, *args: object) -> None:
        self.close()


